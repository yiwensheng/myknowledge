DEFAULT_GENRE = "article"


def list_genres() -> list[dict[str, str | int]]:
    return [
        {
            "id": gid,
            "label": g["label"],
            "description": g.get("description", ""),
            "min_chars": g.get("min_chars", 1000),
        }
        for gid, g in GENRES.items()
    ]


def get_genre(genre_id: str | None) -> dict[str, Any]:
    gid = (genre_id or DEFAULT_GENRE).strip().lower()
    if gid not in GENRES:
        gid = DEFAULT_GENRE
    return {"id": gid, **GENRES[gid]}


def format_genre_block(genre_id: str | None, brief: str = "") -> str:
    g = get_genre(genre_id)
    parts = [
        f"## 文章体例：{g['label']}",
        g.get("outline", "").strip(),
        f"\n**最低篇幅**：约 {g.get('min_chars', 1000)} 汉字（素材充分时应更长）。",
        "**硬性要求**：写完整正文，不得用几条 bullet 敷衍；不得输出「定义+要点」式摘要代替文章。",
    ]
    b = (brief or "").strip()
    if b:
        parts.extend(["", "## 用户补充要求", b])
    return "\n".join(parts).strip()
